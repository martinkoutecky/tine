import { chromium } from "playwright";
import { readFileSync } from "node:fs";
const source = process.argv[2] ?? "docs/app-icon.svg";
const output = process.argv[3] ?? "scripts/app-icon-1024.png";
const svg = readFileSync(source, "utf8");
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1024, height: 1024 }, deviceScaleFactor: 1 });
await p.setContent(`<!doctype html><html><body style="margin:0;padding:0">${svg}</body></html>`);
await p.locator("svg").screenshot({ path: output, omitBackground: true });
await b.close();
console.log(`rendered ${output}`);
