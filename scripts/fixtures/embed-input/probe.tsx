await initParser();
const leaf=(id:string,raw=id,children:any[]=[])=>({id,raw,collapsed:false,children});
let sourcePage="Embed probe";
backend().resolveBlocks=async()=>[{page:sourcePage,kind:"page",blocks:[leaf("source","Source root\nid:: source")]}];
