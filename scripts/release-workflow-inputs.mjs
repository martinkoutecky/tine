#!/usr/bin/env node
// Identity-derived filenames for release.yml. O(1), no artifact scanning.
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { IDENTITY } from "./lib/app-identity.mjs";
import { releaseLayout } from "./release-layout.mjs";
import { releaseChannel, releaseVersion } from "./release-policy.mjs";

export function workflowInputs(lane, conf, repository, identity = IDENTITY) {
  const spec = releaseLayout(conf.version, identity).lanes[lane];
  if (!spec) throw new Error(`unknown release lane: ${lane}`);
  const find = (suffix) => spec.assets.find((name) => name.endsWith(suffix));
  const values = { RELEASE_PRODUCT_NAME: identity.productName };
  const appimage = find(".AppImage");
  if (appimage) {
    values.RELEASE_APPIMAGE = spec.sourceAssets[appimage];
    values.RELEASE_ZSYNC = spec.sourceAssets[`${appimage}.zsync`];
    values.UPDATE_INFORMATION = `gh-releases-zsync|${repository.replace("/", "|")}|${releaseChannel(conf)}|${appimage.replace(conf.version, "*")}.zsync`;
    values.LDAI_UPDATE_INFORMATION = values.UPDATE_INFORMATION;
  }
  if (find("-portable.zip")) values.RELEASE_PORTABLE = find("-portable.zip");
  if (find(".apk")) values.RELEASE_APK = find(".apk");
  return values;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const conf = JSON.parse(fs.readFileSync("src-tauri/tauri.conf.json", "utf8"));
  if (process.argv[2] === "android-config") {
    // Kotlin namespace is the committed Java source package, independent of
    // installation identity. Tauri CLI needs it to locate the generated project.
    const gradle = fs.readFileSync("src-tauri/gen/android/app/build.gradle.kts", "utf8");
    const namespace = gradle.match(/^\s*namespace = "([^"]+)"$/m)?.[1];
    const applicationId = gradle.match(/^\s*applicationId = "([^"]+)"$/m)?.[1];
    if (!namespace || applicationId !== IDENTITY.androidApplicationId) throw new Error("Android identity drift");
    conf.identifier = namespace;
    fs.writeFileSync("src-tauri/tauri.conf.json", JSON.stringify(conf, null, 2) + "\n");
    const { androidCode } = releaseVersion(conf.version);
    fs.writeFileSync("src-tauri/gen/android/app/tauri.properties",
      `// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\ntauri.android.versionName=${conf.version}\ntauri.android.versionCode=${androidCode}\n`);
  } else {
    for (const [name, value] of Object.entries(workflowInputs(process.argv[2], conf,
      process.env.GITHUB_REPOSITORY ?? "martinkoutecky/tine"))) console.log(`${name}=${value}`);
  }
}
