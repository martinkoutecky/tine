#!/usr/bin/env node
// Generates the localization catalog's derivatives (tine#107; never edit them):
// - src/i18n/messages.gen.ts: every English message id with its argument types,
//   and the locale registry (tag, endonym, the language tags it serves);
// - src-tauri/src/i18n_shell.gen.rs: the literal shell messages per locale, which
//   native code selects but never formats (DESIGN rev. 2, review #3).
// `--check` exits 1 when a committed derivative differs (the catalog test runs it).
import fs from "node:fs";
import path from "node:path";
import {
  checkCatalog, literalText, localeMeta, SHELL_FILE, SOURCE_LOCALE, variablesOf,
} from "./lib/i18n-catalog.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const TS_OUT = path.join(ROOT, "src/i18n/messages.gen.ts");
const RS_OUT = path.join(ROOT, "src-tauri/src/i18n_shell.gen.rs");

export function generate() {
  const { errors, locales } = checkCatalog();
  if (errors.length) throw new Error(`catalog errors:\n${errors.join("\n")}`);
  const source = locales.find((locale) => locale.tag === SOURCE_LOCALE);
  const ids = [];
  for (const [id, found] of [...source.entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    if (found.entry.type !== "Message") continue;
    const { names, numeric } = variablesOf(id, source.entries);
    const fields = [...names].sort().map((name) => `${JSON.stringify(name)}: ${numeric.has(name) ? "number" : "string | number"}`);
    const type = fields.length ? `{ ${fields.join("; ")} }` : "{}";
    if (found.entry.value) ids.push(`  ${JSON.stringify(id)}: ${type};`);
    for (const attribute of found.entry.attributes) ids.push(`  ${JSON.stringify(`${id}.${attribute.id.name}`)}: ${type};`);
  }
  const registry = locales.map(localeMeta).map((meta) =>
    `  { tag: ${JSON.stringify(meta.tag)}, name: ${JSON.stringify(meta.name)}, matches: ${JSON.stringify(meta.matches)} },`);
  const ts = `// Generated by scripts/i18n-gen.mjs from src/i18n/locales/*/*.ftl. Do not edit:
// change the catalog and run \`node scripts/i18n-gen.mjs\`.

/** Every English message (and \`message.attribute\`) id, with the arguments it takes. */
export interface MessageArgs {
${ids.join("\n")}
}

export type MessageId = keyof MessageArgs;

/** The shipped locales, source first: tag, endonym, and the language tags each serves. */
export const LOCALES: readonly { readonly tag: string; readonly name: string; readonly matches: readonly string[] }[] = [
${registry.join("\n")}
];
`;
  const shellArms = [];
  for (const locale of locales) {
    const arms = [];
    for (const [id, found] of [...locale.entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
      if (found.file !== SHELL_FILE) continue;
      arms.push(`        (${JSON.stringify(locale.tag)}, ${JSON.stringify(id)}) => Some(${JSON.stringify(literalText(found).text)}),`);
    }
    shellArms.push(...arms);
  }
  const rs = `// Generated by scripts/i18n-gen.mjs from src/i18n/locales/*/${SHELL_FILE}. Do not edit:
// change the catalog and run \`node scripts/i18n-gen.mjs\`. Native code selects
// these literal strings; it never formats a message (docs/contracts/localization.md).

/// The literal shell message \`id\` in \`locale\`, if that locale has it.
pub(crate) fn shell_literal(locale: &str, id: &str) -> Option<&'static str> {
    match (locale, id) {
${shellArms.join("\n")}
        _ => None,
    }
}
`;
  return [[TS_OUT, ts], [RS_OUT, rs]];
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const [file, text] of generate()) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (current === text) continue;
    if (check) {
      console.error(`${path.relative(ROOT, file)} is stale: run node scripts/i18n-gen.mjs`);
      stale = true;
    } else {
      fs.writeFileSync(file, text);
      console.log(`wrote ${path.relative(ROOT, file)}`);
    }
  }
  process.exit(stale ? 1 : 0);
}
